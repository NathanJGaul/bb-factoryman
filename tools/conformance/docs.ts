import type { ResultFile } from "./result.ts";
import { SCENARIOS } from "./scenarios/index.ts";

export const HARNESS_ORDER: readonly string[] = ["claude-code", "codex", "pi", "omp"];

const NAMES: Record<string, string> = { "claude-code": "Claude Code", codex: "Codex", pi: "Pi", omp: "omp" };

const titleOf = (id: string): string => SCENARIOS.find((s) => s.id === id)?.title ?? "";

function rows(result: ResultFile): string[] {
  const order = (id: string) => Number(id.slice(1));
  return [...result.scenarios]
    .sort((a, b) => order(a.id) - order(b.id))
    .map((scenario) => {
      const gaps = scenario.checks.flatMap((check) => (check.gap === undefined ? [] : [{ check: check.id, ...check.gap }]));
      const tasks = [...new Set(gaps.map((gap) => gap.task))].join(", ");
      const verdict = scenario.verdict === "known-gap" ? `known gap (${tasks})` : scenario.verdict;
      const failed = scenario.checks.filter((check) => !check.ok && check.gap === undefined).map((check) => check.id);
      const detail = scenario.verdict === "known-gap" ? gaps.map((gap) => `${gap.check} waits for ${gap.task}: ${gap.reason}`).join("; ") : scenario.verdict === "fail" ? `failed: ${failed.join(", ") || "the scenario threw"}` : "";
      return `| ${scenario.id} | ${verdict} | ${titleOf(scenario.id)} | ${detail} |`;
    });
}

function facts(result: ResultFile): string[] {
  return [
    "| Field | Value |",
    "| --- | --- |",
    `| CLI | ${result.cli.name} ${result.cli.version} |`,
    `| bb | ${result.bb.version} |`,
    `| Plugin commit | ${result.plugin.commit}${result.plugin.dirty ? " (with uncommitted changes)" : ""} |`,
    `| Date | ${result.startedAt.slice(0, 10)} |`,
    `| Network | ${result.offline ? "offline" : "shared"} |`,
    `| Isolation | ${result.isolation.clean ? "clean" : "changed"} |`,
    "",
    "| Scenario | Verdict | Name | Detail |",
    "| --- | --- | --- | --- |",
    ...rows(result),
  ];
}

function status(result: ResultFile | undefined): string {
  if (result === undefined) return "Status: unsupported. No tier 1.5 result exists for this harness.";
  const failed = result.scenarios.filter((s) => s.verdict === "fail").map((s) => s.id);
  if (failed.length > 0 || !result.isolation.clean) {
    const why = [...(failed.length > 0 ? [`scenarios that failed: ${failed.join(", ")}`] : []), ...(result.isolation.clean ? [] : ["the isolation check found a change"])];
    return `Status: not supported at tier 1.5. ${why.join("; ")}.`;
  }
  const gaps = result.scenarios.filter((s) => s.verdict === "known-gap").map((s) => s.id);
  return `Status: supported at tier 1.5${gaps.length > 0 ? `, with known gaps in ${gaps.join(", ")}` : ""}. Tier 2 has not run.`;
}

/**
 * Write the support document from the result files, and from nothing else.
 * The output holds no clock and no machine path, so it is the same for the same results.
 */
export function renderSupport(results: ResultFile[]): string {
  const tier15 = new Map(results.filter((r) => r.tier === "1.5").map((r) => [r.harness, r]));
  const stub = results.find((r) => r.tier === "1");
  const lines = [
    "# Harness support",
    "",
    "This file is generated by `pnpm run conformance:docs` from the result files in `conformance/results/`.",
    "Do not edit it by hand.",
    "",
    "A harness is supported at tier 1.5 when the real command-line tool, behind a scripted fake model and with no credential, passes the scenarios S1 to S9, S11, and S12.",
    "A known gap is a scenario check that waits for a plugin change in the harness-independence report.",
    "A known gap is never a pass.",
    "Tier 2 (a real model) has not run for any harness.",
    "",
  ];
  for (const id of HARNESS_ORDER) {
    const result = tier15.get(id);
    lines.push(`## ${NAMES[id] ?? id}`, "", status(result), "");
    if (result !== undefined) lines.push(...facts(result), "");
  }
  lines.push("## Tier 1 (stub agent)", "");
  if (stub === undefined) lines.push("No tier 1 result exists.", "");
  else lines.push(...facts(stub), "");
  return `${lines.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd()}\n`;
}
